-- ═══════════════════════════════════════════════════════════════════════
-- CONTROLE DE PONTOS — numeração sequencial dos códigos de campo
-- (marco físico, ponto e ponto virtual), prefixo FUOH-M-/FUOH-P-/FUOH-V-.
-- Substitui a planilha "PONTOS CONTROLE.xlsx" que era usada pra evitar
-- que duas equipes/obras usassem o mesmo código de marco/ponto/vértice.
--
-- Alimenta a aba "Controle de Pontos" dentro de Ferramentas Geo no Gestor.
--
-- Execute no Supabase (SQL Editor) antes de usar a aba. Seguro rodar mais
-- de uma vez (idempotente) — inclusive a importação do histórico da
-- planilha, que usa "on conflict do nothing".
-- ═══════════════════════════════════════════════════════════════════════

create table if not exists pontos_controle (
  id uuid primary key default gen_random_uuid(),
  tipo text not null check (tipo in ('marco','ponto','virtual')),
  numero integer not null,
  codigo text not null,               -- Ex: FUOH-M-0620 (guardado literal p/ busca fácil)
  obra_id uuid references obras(id) on delete set null,
  obra_nome text,                     -- nome/fazenda no momento do registro (funciona mesmo sem obra cadastrada)
  observacoes text,
  criado_em timestamptz not null default now()
);

create unique index if not exists pontos_controle_codigo_uidx on pontos_controle(codigo);
create index if not exists pontos_controle_tipo_idx on pontos_controle(tipo, numero desc);

alter table pontos_controle enable row level security;

-- Aberto pra qualquer usuário logado (equipe toda usa em campo), igual às
-- demais ferramentas de Ferramentas Geo — não há módulo RBAC específico.
drop policy if exists pontos_controle_rw_auth on pontos_controle;
create policy pontos_controle_rw_auth on pontos_controle
  for all to authenticated
  using (true)
  with check (true);

